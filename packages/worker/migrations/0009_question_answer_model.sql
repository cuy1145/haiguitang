-- 判定体检：把「模型原本给出的 answer」留痕。
--
-- 背景（线上真实出现过的一条记录）：
--   模型返回 answer=no + explain="否——你问的『…』与事实不符。"，同时命中了**成立**的事实点；
--   事实表复核（decideFromFacts）把结论改写成「是」，而那句 explain 是模型按自己的「否」写的，
--   于是公共记录里出现「主持人：是 … 否——…与事实不符」。
--
-- 只存"有分歧"的那一种：列非空 == 这条判定的结论被事实表改写过。
-- 有了它，事后才能回答"是模型判错还是系统判错"（pnpm audit 的『判定体检』就是这个查询）。
-- 规则拦截 / 判定缓存 / 内置模拟主持人没有模型答案，保持 NULL。
ALTER TABLE questions ADD COLUMN answer_model TEXT;
